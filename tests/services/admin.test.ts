import { afterEach, describe, expect, it } from "vitest";
import { eq } from "drizzle-orm";
import { closeTestDbs } from "@/db/test-db";
import { auditLog, problems, solves, reports, disqualifications } from "@/db/schema";
import { grantSolve, revokeSolve, rescoreContest } from "@/services/grants";
import { fileReport, reviewReport } from "@/services/reports";
import { createContest, publishContest } from "@/services/contest";
import { getLeaderboard } from "@/services/leaderboard";
import { checkSubmission } from "@/services/submission-checker";
import { setup, at, batch, link } from "../helpers";
afterEach(closeTestDbs);
describe("admin operations", () => {
  it("rejects a solve if a report disqualifies its author during the upstream request", async () => {
    const { db, student, other, admin, contestId } = await setup();
    const ps = await db.select().from(problems);
    await grantSolve(db, { adminId: admin.id, userId: student.id, problemId: ps[0].id, acceptedAt: at(5), reason: "Proof", evidence: "https://example.com/p", now: at(181) });
    const report = await fileReport(db, { contestId, reporterId: other.id, targetUserId: student.id, problemId: null, proofUrl: "https://example.com/p", description: "Proof", now: at(182) });
    if (!report.ok) throw new Error("report");
    let release!: () => void;
    let entered!: () => void;
    const waiting = new Promise<void>(resolve => { release = resolve; });
    const started = new Promise<void>(resolve => { entered = resolve; });
    const checking = checkSubmission(db, { profileBio: async () => "", recentAccepted: async () => { entered(); await waiting; return [{ id: "88", slug: ps[3].slug, acceptedAt: at(10) }]; } }, { userId: student.id, link: link("88"), now: at(185) });
    await started;
    await reviewReport(db, { adminId: admin.id, reportId: report.reportId, decision: { kind: "disqualify", reason: "Confirmed" }, now: at(185) });
    release();
    expect(await checking).toMatchObject({ ok: false, reason: "disqualified" });
    expect(await db.select().from(solves)).toHaveLength(1);
  });
  it("grants, revokes, re-grants, rescores and audits with the injected clock", async () => {
    const { db, student, admin, contestId } = await setup();
    const ps = await db.select().from(problems);
    const input = { adminId: admin.id, userId: student.id, problemId: ps[3].id, acceptedAt: at(5), reason: "LeetCode outage", evidence: "https://example.com/proof", now: at(200) };
    await expect(grantSolve(db, { ...input, adminId: student.id })).rejects.toThrow("forbidden");
    expect(await grantSolve(db, { ...input, acceptedAt: at(181 + 1 / 60) })).toMatchObject({ reason: "outside_window" });
    const g = await grantSolve(db, input);
    expect(g).toMatchObject({ ok: true, points: 18 });
    if (!g.ok) throw new Error("grant failed");
    expect(await grantSolve(db, input)).toMatchObject({ reason: "already_solved" });
    await revokeSolve(db, { adminId: admin.id, solveId: g.solveId, reason: "Correction", now: at(201) });
    expect(await getLeaderboard(db, contestId)).toEqual([]);
    expect(await grantSolve(db, { ...input, acceptedAt: at(20) })).toMatchObject({ ok: true, solveId: g.solveId, points: 12 });
    await db.update(solves).set({ points: 99 }).where(eq(solves.id, g.solveId));
    await rescoreContest(db, { adminId: admin.id, contestId, reason: "Repair scores", now: at(202) });
    expect((await getLeaderboard(db, contestId))[0].points).toBe(12);
    const logs = await db.select().from(auditLog);
    expect(logs.map(l => l.action)).toEqual(["grant_solve", "revoke_solve", "grant_solve", "rescore_contest"]);
    expect(logs[0].createdAt).toEqual(at(200));
  });
  it("publishes drafts with audit and checks overlap", async () => {
    const { db, admin } = await setup();
    const id = await createContest(db, { title: "Next", startsAt: at(300), batches: [batch(9)], status: "draft" }, { adminId: admin.id, now: at(-10) });
    expect(await publishContest(db, id, admin.id, at(200))).toBe(true);
    expect(await publishContest(db, id, admin.id, at(201))).toBe(false);
    expect((await db.select().from(auditLog)).map(l => l.action)).toEqual(["create_contest", "publish_contest"]);
  });
  it("validates reports, deduplicates, and scopes review to the reported contest and problem", async () => {
    const { db, student, other, admin, contestId } = await setup();
    const ps = await db.select().from(problems);
    const g = await grantSolve(db, { adminId: admin.id, userId: student.id, problemId: ps[0].id, acceptedAt: at(5), reason: "Proof", evidence: "https://example.com/p", now: at(200) });
    if (!g.ok) throw new Error("grant");
    const base = { contestId, reporterId: other.id, targetUserId: student.id, problemId: ps[0].id, proofUrl: "https://example.com/proof", description: "Evidence of account sharing", now: at(200) };
    expect(await fileReport(db, { ...base, now: at(180) })).toMatchObject({ reason: "contest_not_ended" });
    expect(await fileReport(db, { ...base, reporterId: student.id })).toMatchObject({ reason: "self_report" });
    expect(await fileReport(db, { ...base, proofUrl: "javascript:alert(1)" })).toMatchObject({ reason: "no_proof" });
    const r = await fileReport(db, base);
    if (!r.ok) throw new Error("report");
    expect(await fileReport(db, base)).toMatchObject({ reason: "duplicate" });
    const nextId = await createContest(db, { title: "Next", startsAt: at(300), batches: [batch(9)] });
    const all = await db.select().from(problems);
    const otherGrant = await grantSolve(db, { adminId: admin.id, userId: student.id, problemId: all[12].id, acceptedAt: at(305), reason: "Proof", evidence: "https://example.com/p", now: at(400) });
    if (!otherGrant.ok) throw new Error("grant");
    expect(await reviewReport(db, { adminId: admin.id, reportId: r.reportId, decision: { kind: "revoke_solve", solveId: otherGrant.solveId }, now: at(401) })).toBe(false);
    expect((await db.select().from(reports))[0].status).toBe("pending");
    expect(await reviewReport(db, { adminId: admin.id, reportId: r.reportId, decision: { kind: "revoke_solve", solveId: g.solveId }, now: at(402) })).toBe(true);
    expect(await getLeaderboard(db, contestId)).toEqual([]);
    expect(await getLeaderboard(db, nextId)).toHaveLength(1);
    expect(await reviewReport(db, { adminId: admin.id, reportId: r.reportId, decision: { kind: "dismiss" }, now: at(403) })).toBe(false);
  });
  it("disqualifies without deleting solves and dismisses without score changes", async () => {
    const { db, student, other, admin, contestId } = await setup();
    const [p] = await db.select().from(problems);
    for (const user of [student, other]) await grantSolve(db, { adminId: admin.id, userId: user.id, problemId: p.id, acceptedAt: at(5), reason: "Proof", evidence: "https://example.com/p", now: at(200) });
    const r1 = await fileReport(db, { contestId, reporterId: other.id, targetUserId: student.id, problemId: null, proofUrl: "https://example.com/p", description: "Proof", now: at(200) });
    const r2 = await fileReport(db, { contestId, reporterId: student.id, targetUserId: other.id, problemId: null, proofUrl: "https://example.com/p", description: "Proof", now: at(200) });
    if (!r1.ok || !r2.ok) throw new Error("report");
    await reviewReport(db, { adminId: admin.id, reportId: r1.reportId, decision: { kind: "disqualify", reason: "Confirmed sharing" }, now: at(201) });
    await reviewReport(db, { adminId: admin.id, reportId: r2.reportId, decision: { kind: "dismiss" }, now: at(201) });
    expect((await getLeaderboard(db, contestId)).map(r => r.name)).toEqual(["Bo"]);
    expect(await db.select().from(solves)).toHaveLength(2);
    expect(await db.select().from(disqualifications)).toHaveLength(1);
  });
});
